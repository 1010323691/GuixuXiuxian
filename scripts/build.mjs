// Bundles src/battle into static/arena3d.js. Players and the Python server never run this:
// the bundle is committed, and tests/test_frontend_build.py checks its header hash against src/.
import { build, context } from 'esbuild';
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const SRC = join(ROOT, 'src', 'battle');
const OUT = join(ROOT, 'static', 'arena3d.js');

function files(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? files(path) : [path];
  });
}

// Same recipe as tests/test_frontend_build.py: sorted posix paths, LF-normalised text.
export function sourceHash() {
  const hash = createHash('sha256');
  const inputs = [...files(SRC), join(ROOT, 'package.json')]
    .map((path) => [relative(ROOT, path).split(sep).join('/'), path])
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
  for (const [name, path] of inputs) {
    hash.update(name + '\n');
    hash.update(readFileSync(path, 'utf8').replace(/\r\n/g, '\n') + '\n');
  }
  return hash.digest('hex');
}

// The game already serves one Three.js copy; every bundled library must share it.
const sharedThree = {
  name: 'shared-three',
  setup(b) {
    b.onResolve({ filter: /^three$/ }, () => ({ path: '/vendor/three.module.min.js', external: true }));
  },
};

function options() {
  return {
    entryPoints: [join(SRC, 'index.ts')],
    outfile: OUT,
    bundle: true,
    format: 'esm',
    target: 'es2020',
    minify: true,
    legalComments: 'eof',
    charset: 'utf8',
    plugins: [sharedThree],
    banner: { js: `/* arena3d bundle - generated by scripts/build.mjs from src/battle, do not edit. src-sha256: ${sourceHash()} */` },
    logLevel: 'info',
  };
}

if (process.argv.includes('--watch')) {
  const ctx = await context(options());
  await ctx.watch();
} else {
  await build(options());
}
