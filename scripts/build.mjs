// Header: the first line carries two anchors so neither side can drift unnoticed.
//   src-sha256  - hash of src/battle/** + package.json at build time (what the sources were)
//   body-sha256 - hash of everything after this line (what the shipped code actually is)
// A body edited without a rebuild no longer matches body-sha256, which
// tests/test_frontend_build.py checks without Node. A deliberate rewrite of both
// fields is out of scope: this catches drift, not forgery.
function header(srcSha, bodySha) {
  return `/* arena3d bundle - generated by scripts/build.mjs from src/battle, do not edit. src-sha256: ${srcSha} body-sha256: ${bodySha} */`;
}

function banner(srcSha, bodySha) {
  return [
    header(srcSha, bodySha),
    '/*!',
    ' * Third-party code bundled into this file and shipped to browsers with it:',
    ...BUNDLED_LICENSES.map((line) => ` * - ${line}`),
    ' * Three.js itself is not bundled: it is served as /vendor/three.module.min.js (MIT).',
    ' * Full texts: static/vendor/three.quarks.LICENSE, static/vendor/postprocessing.LICENSE.',
    ' */',
  ].join('\n');
}

// Footer keeps the full MIT text in the distributed file itself (check with `tail -c`).
function footer() {
  const mit = MIT_TEXT.split('\n').map((line) => (line ? ` * ${line}` : ' *')).join('\n');
  return [
    '/*!',
    ' * three.quarks v0.16.0 - MIT License',
    ' * Copyright (c) 2019 Forrest Sun',
    ' *',
    mit,
    ' */',
  ].join('\n');
}

function options(srcSha, bodySha) {
  return {
    entryPoints: [join(SRC, 'index.ts')],
    outfile: OUT,
    bundle: true,
    format: 'esm',
    target: 'es2020',
    minify: true,
    legalComments: 'eof',
    charset: 'utf8',
    plugins: [sharedThree],
    banner: { js: banner(srcSha, bodySha) },
    footer: { js: footer() },
    logLevel: 'info',
  };
}

// The body hash cannot be known before the body exists, so build once to a buffer with a
// placeholder, hash everything after the header line, then build for real. Only the header
// line changes between the two passes, so the hash stays valid; esbuild output is stable.
async function bodyHash(srcSha) {
  const probe = await build({ ...options(srcSha, '0'.repeat(64)), write: false, logLevel: 'silent' });
  const text = probe.outputFiles[0].text;
  const body = text.slice(text.indexOf('\n') + 1);
  return createHash('sha256').update(body, 'utf8').digest('hex');
}

const srcSha = sourceHash();
const bodySha = await bodyHash(srcSha);

if (process.argv.includes('--watch')) {
  const ctx = await context(options(srcSha, bodySha));
  await ctx.watch();
} else {
  await build(options(srcSha, bodySha));
}
