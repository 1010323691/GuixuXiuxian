    def elite_state(self):
        s=self.state;w=s['world'];w['stage']=1;w['region']='chisha'
        w['r3']['growth']['rate_num']=growth.rate_num(s);j=w['r3']['journey']
        for story in G.STORIES[:2]:j['stories'][story['id']]={'progress':[o['amount'] for o in story['objectives']],'claimed':True}
