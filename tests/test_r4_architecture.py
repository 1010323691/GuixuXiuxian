NOW=1_800_000_000


def bucket():
    return {'active':True,'dungeon':None,'r3':{'cadence':cadence.initial_state(0),'runs':{},'daily':{}}}


def start(w,key,now):
    w['r3']['runs'][key]={'eligible':False,'completed':False}
    eligible=cadence.reserve(w,key,{'now':now})
    w['r3']['runs'][key]['eligible']=eligible
    w['dungeon']={'run_id':key}
    return eligible


def done(w,key,success,now):
    if success:w['r3']['runs'][key]['completed']=True
    result=cadence.finish(w,key,success,{'now':now})
    w['dungeon']=None
    return result


class CadenceTests(unittest.TestCase):
    def test_initial_three_and_reservation_occupies_capacity(self):
        w=bucket();self.assertTrue(start(w,'a',0))
        projected=cadence.sync({'world':w},999999)['world']
        self.assertEqual(projected['r3']['cadence']['available'],2)
        self.assertEqual(projected['r3']['cadence']['banked_seconds'],0)
        cadence.validate({'world':projected},check_clock=True)

    def test_success_starts_recovery_then_exact_eight_hour(self):
        w=bucket();start(w,'a',0);done(w,'a',True,1000)
        a=cadence.sync({'world':w},1000+28799)['world']['r3']['cadence']
        self.assertEqual(a['available'],2);self.assertEqual(a['banked_seconds'],28799)
        a=cadence.sync({'world':w},1000+28800)['world']['r3']['cadence']
        self.assertEqual(a['available'],3);self.assertEqual(a['banked_seconds'],0)

    def test_long_offline_cap_and_no_hidden_time_at_full(self):
        w=bucket();start(w,'a',0);done(w,'a',True,0)
        w=cadence.sync({'world':w},999999)['world'];start(w,'b',999999);done(w,'b',True,999999)
        result=cadence.sync({'world':w},999999+28799)['world']['r3']['cadence']
        self.assertEqual(result['available'],2)

    def test_fail_releases_once_and_preserves_existing_partial_recovery(self):
        w=bucket();start(w,'a',0);done(w,'a',True,0)
        w=cadence.sync({'world':w},4000)['world'];start(w,'b',4000)
        self.assertEqual(w['r3']['cadence']['available'],1)
        done(w,'b',False,5000)
        self.assertFalse(cadence.finish(w,'b',False,{'now':5000}))
        self.assertEqual(w['r3']['cadence']['available'],2)
        self.assertEqual(w['r3']['cadence']['banked_seconds'],5000)

    def test_practice_no_reservation_and_same_run_cannot_resurrect_credit(self):
        w=bucket()
        for key in ['a','b','c']:start(w,key,0);done(w,key,True,0)
        self.assertFalse(start(w,'practice',0));self.assertFalse(done(w,'practice',True,0))
        self.assertFalse(cadence.reserve(w,'a',{'now':0}))
        self.assertEqual(w['r3']['cadence']['available'],0)

    def test_backwards_clock_no_negative_or_repeated_credits(self):
        w=bucket();start(w,'a',1000);done(w,'a',True,1000)
        w=cadence.sync({'world':w},5000)['world'];before=copy.deepcopy(w)
        self.assertEqual(cadence.sync({'world':w},2000)['world'],before)
        self.assertEqual(cadence.project({'world':w},{'now':2000})['next_at'],29800)

    def test_projection_is_read_only_and_next_at_null_when_full(self):
        w=bucket();before=copy.deepcopy(w)
        self.assertIsNone(cadence.project({'world':w},{'now':1000})['next_at'])
        self.assertEqual(w,before)

    def test_corrupt_ledger_and_capacity_are_rejected(self):
        w=bucket()
        for field,value in [('available',True),('available',4),('banked_seconds',28800),('banked_seconds',1),('reservations',{'no-run':'reserved'})]:
            bad=copy.deepcopy(w);bad['r3']['cadence'][field]=value
            with self.subTest(field=field,value=value),self.assertRaises(ValueError):cadence.validate({'world':bad},check_clock=True)

    def test_missing_reverse_reservation_is_rejected(self):
        w=bucket();start(w,'active',0)
        w['r3']['cadence']['reservations']={}
        with self.assertRaises(ValueError):cadence.validate({'world':w},check_clock=True)





class ReleasedArchiveMigrationTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.root=tempfile.TemporaryDirectory(prefix='guixu-r4-old-release-')
        cls.folder=Path(cls.root.name)
        fixture_path=Path(__file__).parent/'fixtures'/'r4_v1_1_released_save.json'
        fixture=json.loads(fixture_path.read_text())
        current=fixture['current'];source=fixture['provenance']
        cls.row=(current['schema_version'],current['revision'],encode(current['state']),encode(current['slot']))
        cls.ledger=[(entry['request_id'],entry['payload']) for entry in fixture['requests']]
        assert hashlib.sha256(cls.row[2].encode()).hexdigest()==source['source_state_sha256']
        assert hashlib.sha256(cls.row[3].encode()).hexdigest()==source['source_slot_sha256']
        assert hashlib.sha256(json.dumps(cls.ledger,ensure_ascii=False,separators=(',',':')).encode()).hexdigest()==source['source_requests_sha256']
        cls.original=cls.folder/'old-data';cls.original.mkdir()
        with sqlite3.connect(cls.original/'game.db') as db:
            db.executescript('CREATE TABLE current (id INTEGER PRIMARY KEY CHECK(id=1),schema_version INTEGER NOT NULL,revision INTEGER NOT NULL,state TEXT NOT NULL,slot TEXT NOT NULL);CREATE TABLE requests(request_id TEXT PRIMARY KEY,payload TEXT NOT NULL);')
            db.execute('INSERT INTO current VALUES(1,?,?,?,?)',cls.row)
            db.executemany('INSERT INTO requests VALUES(?,?)',cls.ledger)
        cls.original_bytes=(cls.original/'game.db').read_bytes()
    @classmethod
    def tearDownClass(cls):cls.root.cleanup()
    def setUp(self):
        self.tmp=tempfile.TemporaryDirectory(prefix='guixu-r4-migrate-test-');self.addCleanup(self.tmp.cleanup)
        self.data=Path(self.tmp.name);shutil.copyfile(self.original/'game.db',self.data/'game.db')

    def test_real_old_archive_current_slot_run_activity_and_backup(self):
        s=Store(self.data,clock=lambda:NOW+28800)
        self.assertIsNotNone(s.migration_backup)
        with sqlite3.connect(s.migration_backup) as backup:
            self.assertEqual(backup.execute('SELECT schema_version,revision,state,slot FROM current').fetchone(),self.row)
            self.assertEqual(backup.execute('SELECT * FROM requests ORDER BY request_id').fetchall(),self.ledger)
        self.assertEqual((self.original/'game.db').read_bytes(),self.original_bytes)
        with sqlite3.connect(s.path) as db:
            row=db.execute('SELECT schema_version,revision,state,slot FROM current').fetchone()
            self.assertEqual(db.execute('SELECT * FROM requests ORDER BY request_id').fetchall(),self.ledger)
        self.assertEqual(row[1],self.row[1]+1)
        for old_raw,new_raw in zip(self.row[2:],row[2:]):
            old,new=json.loads(old_raw),json.loads(new_raw);og,ng=old['world']['r3']['growth'],new['world']['r3']['growth']
            elapsed=NOW+28800-og['last_settled']
            expected=(Fraction(og['balance_micro']*growth.DENOMINATOR+og['remainder']+elapsed*og['rate_num'],growth.DENOMINATOR))/6
            actual=Fraction(ng['balance_micro']*ng['remainder_denominator']+ng['remainder'],ng['remainder_denominator'])
            self.assertEqual(actual,expected)
            self.assertEqual(new['world']['stage'],old['world']['stage'])
            self.assertEqual(new['world']['r3']['activities'],old['world']['r3']['activities'])
            self.assertEqual(new['world']['battle'],old['world']['battle'])
            self.assertEqual(new['world']['r3']['cadence']['available'],2)
            self.assertEqual(list(new['world']['r3']['cadence']['reservations'].values()),['reserved'])
            self.assertEqual(ng['curve_version'],2)
            self.assertEqual(ng['total_micro'],og['total_micro']+(elapsed*og['rate_num']+og['remainder'])//growth.DENOMINATOR)
        count=len(list(self.data.glob('*.bak.db')))
        again=Store(self.data,clock=lambda:NOW+28800)
        self.assertIsNone(again.migration_backup)
        self.assertEqual(again.snapshot()['revision'],row[1])
        self.assertEqual(len(list(self.data.glob('*.bak.db'))),count)
        request=json.loads(self.ledger[-1][1]);duplicate=again.write(request['endpoint'],request['payload'])
        self.assertTrue(duplicate['duplicate']);self.assertEqual(duplicate['revision'],row[1])

    def test_sql_failure_rolls_back_current_slot_revision_and_ledger(self):
        with sqlite3.connect(self.data/'game.db') as db:
            db.execute("CREATE TRIGGER deny_r4 BEFORE UPDATE ON current BEGIN SELECT RAISE(ABORT,'r4-update-fault'); END")
        before=(self.data/'game.db').read_bytes()
        with self.assertRaises(sqlite3.IntegrityError):Store(self.data,clock=lambda:NOW+28800)
        self.assertEqual((self.data/'game.db').read_bytes(),before)
        with sqlite3.connect(self.data/'game.db') as db:
            self.assertEqual(db.execute('SELECT schema_version,revision,state,slot FROM current').fetchone(),self.row)
            self.assertEqual(db.execute('SELECT * FROM requests ORDER BY request_id').fetchall(),self.ledger)
        self.assertEqual(len(list(self.data.glob('*.bak.db'))),1)

    def test_backup_failure_preserves_old_bytes(self):
        before=(self.data/'game.db').read_bytes()
        with patch('game.storage.tempfile.mkstemp',side_effect=OSError('backup denied')):
            with self.assertRaises(OSError):Store(self.data,clock=lambda:NOW+28800)
        self.assertEqual((self.data/'game.db').read_bytes(),before)

    def test_non_integral_stage_ratio_and_unspent_overflow_preserved(self):
        with sqlite3.connect(self.data/'game.db') as db:
            raw=json.loads(self.row[2]);w=raw['world'];w['battle']=None;w['dungeon']=None;w['stage']=5;w['xp']=50000
            g=w['r3']['growth'];g['balance_micro']=50000*growth.MICRO+123;g['remainder']=1;g['rate_num']=540*growth.MICRO*65*10000
            raw_original=copy.deepcopy(raw)
            db.execute('UPDATE current SET state=?,slot=?',(json.dumps(raw),json.dumps(raw)))
        migrated=Store(self.data,clock=lambda:NOW).snapshot()['state'];g=migrated['world']['r3']['growth']
        expected=Fraction(raw_original['world']['r3']['growth']['balance_micro']*growth.DENOMINATOR+1,growth.DENOMINATOR)*Fraction(8,7)
        actual=Fraction(g['balance_micro']*g['remainder_denominator']+g['remainder'],g['remainder_denominator'])
        self.assertEqual(actual,expected);self.assertGreater(migrated['world']['xp'],28080)
        self.assertEqual(g['total_micro'],raw_original['world']['r3']['growth']['total_micro'])

    def test_competing_startups_upgrade_once_and_keep_request_ledger(self):
        def launch(_):return Store(self.data,clock=lambda:NOW+28800)
        with ThreadPoolExecutor(max_workers=2) as pool:stores=list(pool.map(launch,range(2)))
        self.assertEqual(sum(s.migration_backup is not None for s in stores),1)
        self.assertEqual(len(list(self.data.glob('*.bak.db'))),1)
        self.assertEqual({s.snapshot()['revision'] for s in stores},{self.row[1]+1})
        with sqlite3.connect(self.data/'game.db') as db:
            self.assertEqual(db.execute('SELECT * FROM requests ORDER BY request_id').fetchall(),self.ledger)

    def test_upgraded_checkpoint_never_restores_old_growth_or_reservation(self):
        s=Store(self.data,clock=lambda:NOW+28800);before=s.snapshot()
        after=s.write('load',{'request_id':'r4-load','expected_revision':before['revision']})
        self.assertEqual(after['state'],before['state'])
        self.assertEqual(after['state']['world']['battle']['turn'],1)
        self.assertEqual(after['state']['world']['r3']['cadence']['available'],2)

    def test_sealed_realm_preserves_actual_reserve_and_historical_production(self):
        old=json.loads(self.row[2]);w=old['world'];w['battle']=None;w['dungeon']=None
        w['stage']=7;w['ending']=True;w['guard_wins']=['7'];w['xp']=123
        g=w['r3']['growth'];g['balance_micro']=123*growth.MICRO+1;g['remainder']=2
        g['rate_num']=540*growth.MICRO*120*10000
        new=growth.upgrade_legacy(old,NOW);ng=new['world']['r3']['growth']
        expected=Fraction(g['balance_micro']*growth.DENOMINATOR+2,growth.DENOMINATOR)
        self.assertEqual(Fraction(ng['balance_micro']*ng['remainder_denominator']+ng['remainder'],ng['remainder_denominator']),expected)
        self.assertTrue(new['world']['ending']);self.assertEqual(new['world']['stage'],7)
        self.assertEqual(ng['total_micro'],g['total_micro'])
        self.assertEqual(new['world']['xp'],w['xp'])

    def test_free_and_empty_databases_do_not_upgrade_or_create_backup(self):
        with tempfile.TemporaryDirectory() as folder:
            store=Store(folder,clock=lambda:NOW)
            self.assertIsNone(Store(folder,clock=lambda:NOW+28800).migration_backup)
            self.assertEqual(store.snapshot()['revision'],0)
            store.write('new-game',{'request_id':'free','expected_revision':0,'name':'旧自由','mode':'free'})
            before=store.path.read_bytes()
            again=Store(folder,clock=lambda:NOW+28800)
            self.assertEqual(again.path.read_bytes(),before)
            self.assertEqual(again.snapshot()['revision'],1)
            self.assertIsNone(again.migration_backup)


class CrossModuleReviewTests(unittest.TestCase):
    def setUp(self):
        source=json.loads((Path(__file__).parent/'fixtures'/'r4_v1_1_released_save.json').read_text())['current']['state']
        self.state=growth.upgrade_legacy(source,NOW)
        self.state=cadence.migrate_legacy(self.state,NOW);journey.migrate(self.state['world'])
        w=self.state['world'];loot.release_run(w);w['battle']=None;w['dungeon']=None
        self.context={'now':NOW,'day':'2027-01-15'}

    def elite_state(self):
        s=self.state;w=s['world'];w['stage']=1;w['region']='chisha'
        w['r3']['growth']['rate_num']=growth.rate_num(s);j=w['r3']['journey']
        for story in G.STORIES[:2]:j['stories'][story['id']]={'progress':[o['amount'] for o in story['objectives']],'claimed':True}
        story=G.STORIES[2];j['stories'][story['id']]={'progress':[0,0],'claimed':False}
        s,_=rules.apply_action(s,'world_elite_enter',{'elite':'caravan_guard'},context=self.context)
        rules.validate_state(s)
        return s

    def test_legal_elite_and_reverse_story_receipt_region_consistency(self):
        s=self.elite_state()
        for mutation in ['region','already_won','unclaimed_receipt','malformed_receipts']:
            with self.subTest(mutation=mutation):
                broken=copy.deepcopy(s);w=broken['world']
                if mutation=='region':w['region']='qinglan'
                elif mutation=='already_won':w['r3']['journey']['elite_wins'].append('caravan_guard')
                elif mutation=='malformed_receipts':w['r3']['receipts']=[];w['r3']['journey']['stories']['caravan_rescue']['progress']=[True,0]
                else:w['r3']['receipts'].append({'id':'bad-receipt','uid':'bad-uid','template':'blade','quality':1,'source':'story:'+w['r3']['profile_id']+':caravan_rescue'})
                original=copy.deepcopy(broken)
                with self.assertRaises(ValueError):rules.validate_state(broken)
                self.assertEqual(broken,original)

    def test_sweep_uses_one_credit_shared_repeat_rewards_one_tick_and_no_resources(self):
        s=self.state;w=s['world'];w['dungeon_wins']=['den:0:1'];w['r3']['journey']['manual_clears']=['den:0:1']
        rules.validate_state(s);before=copy.deepcopy(w)
        result,_=rules.apply_action(s,'world_dungeon_sweep',{'dungeon':'den','chapter':0,'difficulty':1},context=self.context)
        a=result['world'];r=a['r3']
        self.assertEqual((a['hp'],a['mp']),(before['hp'],before['mp']))
        self.assertEqual(a['tick'],before['tick']+1)
        self.assertEqual(result['actions_taken'],s['actions_taken']+1)
        self.assertEqual(a['wallet'],before['wallet']+10)
        self.assertEqual(a['inventory']['herb'],before['inventory']['herb']+3)
        self.assertEqual(r['cadence']['available'],before['r3']['cadence']['available']-1)
        self.assertEqual(r['pity']['1'],before['r3']['pity']['1']+1)
        self.assertEqual(r['drop_seq'],before['r3']['drop_seq']+1)
        self.assertEqual(r['materials']['dust'],before['r3']['materials']['dust']+2)
        self.assertEqual(r['materials']['enhance_material'],before['r3']['materials']['enhance_material']+2)
        self.assertEqual(r['journey']['manual_clears'],before['r3']['journey']['manual_clears'])
        self.assertEqual(a['counters']['battles'],before['counters']['battles'])
        self.assertEqual(a['counters']['wins'],before['counters']['wins'])
        self.assertFalse(r['runs'][max(r['runs'],key=lambda key:int(key.rsplit(':',1)[1]))]['manual'])


